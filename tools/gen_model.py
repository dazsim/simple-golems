#!/usr/bin/env python3
# writes client/GolemMesh.java from tools/golem_b.json (y up, faces +z) in vanilla model space (y down, faces -z), run from repo root
import json, math

SRC = "tools/golem_b.json"
OUT = "common/src/main/java/com/workshopcraft/simplegolems/client/GolemMesh.java"


def f(v):
    v = round(v + 0.0, 4)
    if v == 0:
        v = 0.0
    return f"{v}F"


def main():
    model = json.load(open(SRC))
    bones = {b["name"]: b for b in model["bones"]}
    tw, th = model["texture_size"]
    lines = []
    order = []

    def visit(name):
        if name in order:
            return
        b = bones[name]
        if b.get("parent"):
            visit(b["parent"])
        order.append(name)

    for b in model["bones"]:
        visit(b["name"])
    for name in order:
        b = bones[name]
        px, py, pz = b["pivot"]
        parent = b.get("parent")
        if parent:
            qx, qy, qz = bones[parent]["pivot"]
            off = (px - qx, -(py - qy), -(pz - qz))
            holder = f"p_{parent}"
        else:
            off = (px, -py, -pz)
            holder = "root"
        rx, ry, rz = b.get("rotation", [0, 0, 0])
        cubes = []
        for c in b["cubes"]:
            ox, oy, oz = c["origin"]
            w, h, d = c["size"]
            u, v = c["uv"]
            inf = c.get("inflate", 0.0)
            box = f"addBox({f(ox - px)}, {f(py - oy - h)}, {f(pz - oz - d)}, {f(w)}, {f(h)}, {f(d)}"
            box += f", new CubeDeformation({f(inf)}))" if inf else ")"
            cubes.append(f".texOffs({u}, {v}).{box}")
        pose = f"PartPose.offsetAndRotation({f(off[0])}, {f(off[1])}, {f(off[2])}, {f(math.radians(rx))}, {f(math.radians(-ry))}, {f(math.radians(-rz))})"
        lines.append(f"        PartDefinition p_{name} = {holder}.addOrReplaceChild(\"{name}\", CubeListBuilder.create()"
                     + "".join(f"\n                {c}" for c in cubes) + f",\n                {pose});")
    body = "\n".join(lines)
    java = f"""package com.workshopcraft.simplegolems.client;

import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;

// generated by tools/gen_model.py from tools/golem_b.json
public final class GolemMesh {{
    private GolemMesh() {{}}

    @SuppressWarnings("unused")
    public static LayerDefinition create() {{
        MeshDefinition mesh = new MeshDefinition().transformed(p -> p.translated(0.0F, 24.0F, 0.0F));
        PartDefinition root = mesh.getRoot();
{body}
        return LayerDefinition.create(mesh, {tw}, {th});
    }}
}}
"""
    open(OUT, "w").write(java)


main()
